"""Render an audit as text, JSON or a self-contained HTML page."""

from __future__ import annotations

import html
import json

from .score import Audit, Finding

LABELS = {
    "critical": "CRITICAL",
    "high": "HIGH",
    "medium": "MEDIUM",
    "low": "LOW",
    "info": "INFO",
}


def to_json(report: Audit) -> str:
    return json.dumps(report.as_dict(), indent=2, sort_keys=True)


def to_text(report: Audit) -> str:
    lines = [
        f"mailposture · {report.domain}",
        f"Grade {report.grade}     score {report.score}/100     "
        f"{len(report.findings)} finding(s)",
        "=" * 72,
    ]
    if not report.findings:
        lines.append("Nothing to report.")
    for finding in report.sorted_findings():
        lines.append(f"[{LABELS.get(finding.severity, finding.severity):<8}] "
                     f"{finding.id}  {finding.title}")
        for chunk in _wrap(finding.detail, 68):
            lines.append(f"           {chunk}")
        if finding.remediation:
            for chunk in _wrap("fix: " + finding.remediation, 68):
                lines.append(f"           {chunk}")
        lines.append("")

    facts = report.facts
    lines.append("-" * 72)
    lines.append(f"SPF     {facts.get('spf', {}).get('record') or '(none)'}")
    dmarc = facts.get("dmarc", {})
    lines.append(f"DMARC   {dmarc.get('record') or '(none)'}")
    mx = ", ".join(f"{m['preference']} {m['host']}" for m in facts.get("mx", []))
    lines.append(f"MX      {mx or '(none)'}")
    dkim = ", ".join(
        f"{k['selector']}:{k['bits'] or '?'}bit"
        + (" revoked" if k["revoked"] else "")
        for k in facts.get("dkim", [])
    )
    lines.append(f"DKIM    {dkim or '(no key on probed selectors)'}")
    lookups = facts.get("spf", {}).get("lookups")
    if lookups is not None:
        lines.append(f"SPF DNS lookups  {lookups}/10   void {facts['spf'].get('void_lookups')}/2")
    return "\n".join(lines) + "\n"


def _wrap(text: str, width: int) -> list[str]:
    words, lines, current = text.split(), [], ""
    for word in words:
        if len(current) + len(word) + 1 > width:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}".strip()
    if current:
        lines.append(current)
    return lines or [""]


def to_html(report: Audit) -> str:
    rows = []
    for finding in report.sorted_findings():
        rows.append(
            f"<tr class='{finding.severity}'><td>{html.escape(finding.severity)}</td>"
            f"<td><code>{html.escape(finding.id)}</code></td>"
            f"<td><strong>{html.escape(finding.title)}</strong><br>"
            f"<span class='detail'>{html.escape(finding.detail)}</span>"
            + (f"<br><span class='fix'>fix: {html.escape(finding.remediation)}</span>"
               if finding.remediation else "")
            + "</td></tr>"
        )
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>mailposture · {html.escape(report.domain)}</title>
<style>
 body{{font:15px/1.5 system-ui,sans-serif;margin:2rem auto;max-width:60rem;color:#1b1d22}}
 h1{{font-size:1.4rem;margin:0}} .grade{{float:right;font-size:2rem;font-weight:700}}
 table{{width:100%;border-collapse:collapse;margin-top:1rem}}
 td,th{{padding:.55rem .6rem;border-bottom:1px solid #e6e8ec;vertical-align:top;text-align:left}}
 tr.critical td:first-child{{color:#b3261e;font-weight:700}}
 tr.high td:first-child{{color:#c7511f;font-weight:700}}
 tr.medium td:first-child{{color:#8a6d00;font-weight:700}}
 tr.low td:first-child{{color:#4a5a76}}
 tr.info td:first-child{{color:#6b7280}}
 .detail{{color:#33363d}} .fix{{color:#3a6b35}}
 footer{{margin-top:2rem;color:#6b7280;font-size:.85rem}}
</style></head><body>
<h1>mailposture · {html.escape(report.domain)}
<span class="grade">Grade {report.grade} · {report.score}/100</span></h1>
<table><thead><tr><th>severity</th><th>check</th><th>finding</th></tr></thead>
<tbody>{''.join(rows) or '<tr><td colspan=3>Nothing to report.</td></tr>'}</tbody></table>
<footer>Generated by mailposture. Findings are point-in-time observations, not a
compliance certification.</footer></body></html>
"""
